#!/usr/bin/env python3
"""APIのエラーを、日本語の説明に置き換えて止める（第2部・付録C）

生のトレースバックが出ても、プログラミングを知らない方には何も伝わりません。
「何が起きて、次に何をすればよいか」だけを日本語で出します。
"""
import sys, urllib.error, json

_MSG = {
    401: ("キーが違うか、期限が切れています",
          ["・.env のキーを見直してください（前後に空白や引用符が入っていませんか）",
           "・サービスの画面で新しいキーを作り直すと、確実です"]),
    403: ("そのプランでは使えない操作です",
          ["・無料プランでは使えない声・機能の可能性があります",
           "・プランの内容をご確認ください"]),
    404: ("指定したものが見つかりません",
          ["・voice_id が正しいか確認してください（/00_声を選ぶ）"]),
    422: ("送った内容が受け付けられませんでした",
          ["・台本に、使えない文字が入っていないか確認してください"]),
    429: ("短い時間に作りすぎです（順番待ち）",
          ["・1〜2分ほど置いて、もう一度実行してください",
           "・作ったものは残っているので、続きから進みます"]),
}
_QUOTA = ("今月の文字数、または残高が足りません",
          ["・サービスの画面で、残りの文字数と残高を確認してください",
           "・翌月まで待つか、プランを上げるかの判断になります"])


def die(e, where=""):
    """urllib のエラーを、日本語で説明して終了する"""
    code = getattr(e, "code", None)
    detail = ""
    try:
        detail = e.read().decode("utf-8", "ignore")[:400]
    except Exception:
        pass
    if code == 402 or (code == 401 and "quota" in detail.lower()):
        title, hints = _QUOTA
    else:
        title, hints = _MSG.get(code, ("うまく通信できませんでした",
                                       ["・インターネットにつながっているか確認してください",
                                        "・少し時間を置いて、もう一度お試しください"]))
    print("\n────────────────────────────────")
    print(f"  {title}")
    print("────────────────────────────────")
    if where:
        print(f"  どこで：{where}")
    if code:
        print(f"  応答コード：{code}")
    print()
    for h in hints:
        print(" ", h)
    print()
    print("  解決しないときは、ここから下をそのままClaudeに貼ってください。")
    print("  ---")
    print(f"  {type(e).__name__}: {e}")
    if detail:
        print(f"  {detail}")
    print("  ---\n")
    sys.exit(1)
